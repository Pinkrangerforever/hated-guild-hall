"""Bundle the shared Guild War code (map data, engine, AI) into one ES module for the `war` Edge Function.

The browser loads guild-war/map-data.js, engine.js and ai.js as plain scripts; the Edge Function (Deno) needs a
module. This glues the three files together and exports what they define, so the server runs exactly the same
rules as the war room. Run it after changing any of those files (CI runs it before every deploy):

  python tools/build_war_server.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = ['guild-war/map-data.js', 'guild-war/engine.js', 'guild-war/ai.js']
OUT = os.path.join(ROOT, 'supabase', 'functions', 'war', 'game.js')

parts = ['// GENERATED by tools/build_war_server.py from ' + ', '.join(SRC) + ' - do not edit by hand.\n']
for rel in SRC:
    parts.append(f'\n// ===== {rel} =====\n')
    parts.append(open(os.path.join(ROOT, rel), encoding='utf-8').read())
parts.append('''
// ===== exports =====
export const E = globalThis.WarEngine;
export const AI = globalThis.WarAI;
export const MAP = { WAR_ZONES, WAR_REGIONS, WAR_STRONGHOLDS };
''')
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', encoding='utf-8', newline='\n').write(''.join(parts))
print('wrote', os.path.relpath(OUT, ROOT))

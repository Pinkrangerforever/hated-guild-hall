"""Write the card catalog migration (tcg_cards rows) from the renderer's manifest.json.

    python tools/tcg_art/make_card_migration.py  ->  supabase/migrations/20261020000200_tcg_card_catalog.sql

Only names / stats / rarity go in (no card text or art); the images live in R2 under tcg/cards/<id>.webp.
"""
import json, os, sys

SRC = os.path.join(os.path.expanduser('~'), 'Documents', 'Hearthstone Art', 'manifest.json')
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'supabase', 'migrations', '20261020000200_tcg_card_catalog.sql')
OURS = {'FREE': 'common', 'COMMON': 'uncommon', 'RARE': 'rare', 'EPIC': 'epic', 'LEGENDARY': 'legendary'}


def q(v):
    if v is None or v == '':
        return 'NULL'
    if isinstance(v, (int, float)):
        return str(int(v))
    return "'" + str(v).replace("'", "''") + "'"


cards = json.load(open(sys.argv[1] if len(sys.argv) > 1 else SRC, encoding='utf-8'))
rows = []
for c in cards:
    r = OURS.get(c.get('rarity'))
    if not r:
        continue
    rows.append('(' + ', '.join(q(x) for x in (c['id'], c['name'], c.get('set'), c.get('cardClass'), c.get('type'), r,
                                                c.get('cost'), c.get('attack'), c.get('health') or c.get('durability'))) + ')')
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('-- Migration: Hated TCG card catalog (generated by tools/tcg_art/make_card_migration.py - re-run it, don\'t hand edit)\n')
    f.write(f'-- {len(rows)} cards. Images: https://assets.hatedforever.com/tcg/cards/<id>.webp\n-- Date: 2026-10-20\n\n')
    f.write('INSERT INTO public.tcg_cards (id, name, set_code, card_class, card_type, rarity, cost, attack, health) VALUES\n')
    f.write(',\n'.join(rows))
    f.write('\nON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, set_code = EXCLUDED.set_code, card_class = EXCLUDED.card_class,\n'
            '  card_type = EXCLUDED.card_type, rarity = EXCLUDED.rarity, cost = EXCLUDED.cost, attack = EXCLUDED.attack, health = EXCLUDED.health;\n')
print(f'wrote {len(rows)} cards to {os.path.normpath(OUT)}')

CREATE TABLE IF NOT EXISTS public.tcg_decks (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  name       text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 30),
  hero_id    text NOT NULL REFERENCES public.tcg_cards(id),
  cards      text[] NOT NULL DEFAULT '{}',
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS tcg_decks_user ON public.tcg_decks (user_id, updated_at DESC);

CREATE OR REPLACE FUNCTION public.tcg_deck_check()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  hero_class text;
  bad        text;
BEGIN
  NEW.user_id := coalesce(auth.uid(), NEW.user_id);
  NEW.updated_at := now();
  IF TG_OP = 'INSERT' AND (SELECT count(*) FROM tcg_decks WHERE user_id = NEW.user_id) >= 18 THEN
    RAISE EXCEPTION 'you can keep up to 18 decks';
  END IF;
  SELECT c.card_class INTO hero_class FROM tcg_cards c
    JOIN tcg_collection o ON o.card_id = c.id AND o.user_id = NEW.user_id AND o.count > 0
   WHERE c.id = NEW.hero_id AND c.id LIKE 'HERO_%';
  IF hero_class IS NULL THEN RAISE EXCEPTION 'pick a hero you own'; END IF;
  IF coalesce(array_length(NEW.cards, 1), 0) > 30 THEN RAISE EXCEPTION 'a deck holds 30 cards'; END IF;

  SELECT c.name INTO bad
    FROM (SELECT unnest(NEW.cards) AS id) u
    LEFT JOIN tcg_cards c ON c.id = u.id
   WHERE c.id IS NULL OR c.id LIKE 'HERO_%' OR c.card_class NOT IN ('NEUTRAL', hero_class)
   LIMIT 1;
  IF FOUND THEN RAISE EXCEPTION '% can''t go in a % deck', coalesce(bad, 'that card'), initcap(hero_class); END IF;

  SELECT c.name INTO bad
    FROM (SELECT u.id, count(*) AS n FROM unnest(NEW.cards) AS u(id) GROUP BY u.id) d
    JOIN tcg_cards c ON c.id = d.id
    LEFT JOIN tcg_collection o ON o.card_id = d.id AND o.user_id = NEW.user_id
   WHERE d.n > (CASE WHEN c.rarity = 'legendary' THEN 1 ELSE 2 END) OR d.n > coalesce(o.count, 0)
   LIMIT 1;
  IF FOUND THEN RAISE EXCEPTION 'too many copies of %', bad; END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS tcg_deck_check ON public.tcg_decks;
CREATE TRIGGER tcg_deck_check BEFORE INSERT OR UPDATE ON public.tcg_decks FOR EACH ROW EXECUTE FUNCTION public.tcg_deck_check();

ALTER TABLE public.tcg_decks ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tcg_decks_read ON public.tcg_decks;
